#!/usr/bin/env -S node --import tsx

import { mkdirSync, readFileSync, writeFileSync } from 'fs';
import { LLParse } from 'llparse';
import { dirname, resolve } from 'path';
import { CHeaders, HTTP } from '../src/llhttp';

// https://semver.org/#is-there-a-suggested-regular-expression-regex-to-check-a-semver-string
// eslint-disable-next-line @stylistic/max-len
const semverRE = /^(?<major>0|[1-9]\d*)\.(?<minor>0|[1-9]\d*)\.(?<patch>0|[1-9]\d*)(?:-(?<prerelease>(?:0|[1-9]\d*|\d*[a-zA-Z-][0-9a-zA-Z-]*)(?:\.(?:0|[1-9]\d*|\d*[a-zA-Z-][0-9a-zA-Z-]*))*))?(?:\+(?<buildmetadata>[0-9a-zA-Z-]+(?:\.[0-9a-zA-Z-]+)*))?$/;

const C_FILE = resolve(__dirname, '../build/c/llhttp.c');
const HEADER_FILE = resolve(__dirname, '../build/llhttp.h');
const SSE42_RENAME_FILE = resolve(__dirname, '../build/c/llhttp_sse42_rename.h');
const SSE42_C_FILE = resolve(__dirname, '../build/c/llhttp_sse42.c');

const pkg = JSON.parse(
  readFileSync(resolve(__dirname, '..', 'package.json')).toString(),
);

const version = pkg.version.match(semverRE)?.groups;
const llparse = new LLParse('llhttp__internal');

const cHeaders = new CHeaders();
const nativeHeaders = readFileSync(resolve(__dirname, '../src/native/api.h'));
const generated = llparse.build(new HTTP(llparse).build().entry, {
  c: {
    header: 'llhttp',
  },
  debug: process.env.LLPARSE_DEBUG ? 'llhttp__debug' : undefined,
  headerGuard: 'INCLUDE_LLHTTP_ITSELF_H_',
});

const headers = `
#ifndef INCLUDE_LLHTTP_H_
#define INCLUDE_LLHTTP_H_

#define LLHTTP_VERSION_MAJOR ${version.major}
#define LLHTTP_VERSION_MINOR ${version.minor}
#define LLHTTP_VERSION_PATCH ${version.patch}

${generated.header}

${cHeaders.build()}

${nativeHeaders}

#endif  /* INCLUDE_LLHTTP_H_ */
`;

mkdirSync(dirname(C_FILE), { recursive: true });
writeFileSync(HEADER_FILE, headers);
writeFileSync(C_FILE, generated.c);

// A second instantiation of the generated parser, compiled with -msse4.2, lets
// llhttp_execute() use the SSE4.2 span scanners at runtime on default x86-64
// builds (which pass no -march, so the `#ifdef __SSE4_2__` code is otherwise
// dead). The parser defines symbols prefixed `llhttp__internal`; the callbacks
// it imports are prefixed `llhttp__on`/`llhttp__before`/`llhttp__after` and stay
// shared. Rename only the defined `llhttp__internal*` symbols so the second copy
// links beside the first. Derived from the generated source, so it stays correct
// across grammar changes.
const internalSymbols = Array.from(
  new Set(generated.c.match(/\bllhttp__internal[0-9A-Za-z_]*/g) ?? []),
).sort();
const renameHeader = `/* Generated by bin/generate.ts. Renames the defined symbols of llhttp.c so a
 * second, -msse4.2 instantiation (llhttp_sse42.c) can link beside the first. */
#ifndef INCLUDE_LLHTTP_SSE42_RENAME_H_
#define INCLUDE_LLHTTP_SSE42_RENAME_H_
${internalSymbols.map((s) => `#define ${s} ${s}_sse42`).join('\n')}
#endif  /* INCLUDE_LLHTTP_SSE42_RENAME_H_ */
`;
const sse42Wrapper = `/* Generated by bin/generate.ts. See src/native/api.c: a second instantiation of
 * the generated parser with the SSE4.2 span scanners enabled, selected once at
 * runtime by llhttp_execute(). Built with -msse4.2 by the build system. */
#if defined(__x86_64__) || defined(_M_X64)
#include "llhttp_sse42_rename.h"
#include "llhttp.c"
#endif
`;
writeFileSync(SSE42_RENAME_FILE, renameHeader);
writeFileSync(SSE42_C_FILE, sse42Wrapper);
